"""Measure what Macenko and Reinhard actually do to PBC images (Model 2 diagnostics).

Usage: python scripts/stain_diagnostics.py

Writes reports/stain_normalisation.md. PBC only; no target-domain image is opened.

Why this exists: Model 2a (Macenko) behaves badly on this data, and a bare macro-F1 in
the final table would leave that uninterpretable. These three measurements separate "the
method was implemented wrong" from "the method's assumptions do not hold here":

  1. Self-map error. Normalising the reference image against itself must be the
     identity. A method that cannot reproduce its own reference is miscalibrated.
  2. Tint-gap reduction. Two differently tinted copies of one image should end up
     closer together. That is the entire purpose of stain normalisation.
  3. Tissue-pixel fraction. Macenko estimates stain vectors from pixels stained in
     every channel. If almost none qualify, the estimate is built on a sliver of the
     image and the two-stain model cannot represent the rest.

Reported per class, because eosinophil granules act as a third stain and a two-stain
model has nowhere to put them.
"""
import csv
import sys
import time
from collections import defaultdict
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw"
TRAIN_CSV = RAW / "pbc_attr_v1_train.csv"
OUT = ROOT / "reports" / "stain_normalisation.md"

PER_CLASS = 8                      # images sampled per class
WARM = (1.15, 0.95, 0.90)          # the two synthetic lab tints compared
COOL = (0.90, 0.98, 1.20)
SAMPLE_SEED = 0


def tinted(array, tint):
    return np.clip(array * np.asarray(tint), 0, 255).astype(np.uint8)


def mean_rgb(image):
    return np.asarray(image, dtype=float).mean(axis=(0, 1))


def main():
    sys.path.insert(0, str(ROOT))
    from src.data.mapping import load_label_space
    from src.data.stain import OD_WHITE_THRESHOLD, build_normalizer, load_reference, optical_density

    reference = load_reference()
    excluded = load_label_space().excluded_image_names()
    with open(TRAIN_CSV, newline="", encoding="utf-8") as fh:
        rows = [r for r in csv.DictReader(fh) if r["img_name"] not in excluded]

    by_class = defaultdict(list)
    for row in rows:
        by_class[row["label"]].append(row)
    rng = np.random.RandomState(SAMPLE_SEED)
    sample = []
    for label in sorted(by_class):
        chosen = rng.choice(len(by_class[label]), size=PER_CLASS, replace=False)
        sample += [by_class[label][i] for i in chosen]
    print(f"sampling {len(sample)} PBC train images ({PER_CLASS} per class)...", flush=True)

    normalizers = {name: build_normalizer(name, reference) for name in ("macenko", "reinhard")}
    results = {name: defaultdict(list) for name in normalizers}
    tissue_fraction = []

    for row in sample:
        array = np.asarray(Image.open(RAW / row["path"]).convert("RGB"), dtype=float)
        od = optical_density(array).reshape(-1, 3)
        tissue_fraction.append(float((od >= OD_WHITE_THRESHOLD).all(axis=1).mean()))

        warm = Image.fromarray(tinted(array, WARM))
        cool = Image.fromarray(tinted(array, COOL))
        gap_before = abs(mean_rgb(warm) - mean_rgb(cool)).mean()
        for name, normalizer in normalizers.items():
            started = time.time()
            gap_after = abs(mean_rgb(normalizer(warm)) - mean_rgb(normalizer(cool))).mean()
            results[name][row["label"]].append((gap_before, gap_after, (time.time() - started) / 2))

    # Self-map: normalising the reference against itself.
    reference_image = Image.open(reference["absolute_path"]).convert("RGB")
    before = mean_rgb(reference_image)
    self_map = {name: mean_rgb(n(reference_image)) for name, n in normalizers.items()}

    def table(headers, body):
        out = ["| " + " | ".join(headers) + " |", "|" + "|".join("---" for _ in headers) + "|"]
        return "\n".join(out + ["| " + " | ".join(str(c) for c in r) + " |" for r in body])

    L = [
        "# Stain normalisation diagnostics (Model 2)",
        "",
        f"Generated by `scripts/stain_diagnostics.py` on {time.strftime('%Y-%m-%d %H:%M:%S')}. "
        f"{len(sample)} PBC train images, {PER_CLASS} per class. No target-domain image is read.",
        "",
        f"Reference image: `{reference['path']}`, chosen from PBC train by "
        f"`scripts/choose_stain_reference.py`.",
        "",
        "## 1. Self-map: does each method reproduce its own reference?",
        "",
        "Normalising the reference image against itself should be the identity. Mean RGB:",
        "",
        table(["method", "before", "after", "max channel shift"],
              [[name, np.round(before, 1).tolist(), np.round(after, 1).tolist(),
                round(float(abs(before - after).max()), 1)]
               for name, after in self_map.items()]), "",
        "## 2. Tint-gap reduction: do two 'labs' converge?",
        "",
        "Each image is tinted two ways "
        f"(warm {WARM}, cool {COOL}) and normalised. "
        "`after` below should be far smaller than `before`; a value above `before` means the "
        "method *increased* the colour difference it exists to remove.",
        "",
    ]
    for name in normalizers:
        rows_out = []
        for label in sorted(results[name]):
            data = np.array([(b, a) for b, a, _ in results[name][label]])
            worse = int((data[:, 1] > data[:, 0]).sum())
            rows_out.append([label, round(float(data[:, 0].mean()), 2),
                             round(float(data[:, 1].mean()), 2),
                             f"{worse}/{len(data)}"])
        every = np.array([(b, a) for label in results[name] for b, a, _ in results[name][label]])
        rows_out.append(["**all**", round(float(every[:, 0].mean()), 2),
                         round(float(every[:, 1].mean()), 2),
                         f"{int((every[:, 1] > every[:, 0]).sum())}/{len(every)}"])
        timings = [t for label in results[name] for _, _, t in results[name][label]]
        L += [f"**{name}**", "",
              table(["class", "gap before", "gap after", "made worse"], rows_out), "",
              f"Cost: {1000 * float(np.mean(timings)):.0f} ms per image.", ""]

    L += [
        "## 3. Tissue-pixel fraction",
        "",
        f"Macenko estimates its stain vectors only from pixels whose optical density is at "
        f"least {OD_WHITE_THRESHOLD} in **every** channel. Across the sample, "
        f"**{100 * float(np.mean(tissue_fraction)):.1f}%** of pixels qualify "
        f"(min {100 * min(tissue_fraction):.1f}%, max {100 * max(tissue_fraction):.1f}%).",
        "",
        "## Interpretation",
        "",
        "Macenko assumes H&E histology: a near-white background with the whole field stained,",
        "and exactly two stains. PBC is Wright-Giemsa-stained single cells on a tinted pink",
        "background, so the great majority of each crop is background that the two-stain model",
        "has no way to represent, and the estimated stain vectors carry almost no blue",
        "absorbance. Eosinophils are the worst case: their red granules act as a third stain.",
        "",
        "This was checked against `torchstain`, the standard implementation, and against a",
        "from-scratch implementation of the 2009 paper. Both behave the same way, so the cause",
        "is the method's assumptions, not a coding error. Model 2a is therefore run unmodified,",
        "and its result should be read as evidence about the method's applicability to blood",
        "smears rather than as a tuning failure.",
        "",
        "Reinhard makes no such assumption -- it matches per-channel LAB mean and standard",
        "deviation -- and behaves correctly on the same images.",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
