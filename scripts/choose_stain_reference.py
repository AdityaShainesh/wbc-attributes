"""Choose the stain reference image, from the PBC train split alone.

    python -m scripts.choose_stain_reference --config configs/stain_reinhard.yaml

Writes configs/stain_reference.yaml.

Macenko and Reinhard are both defined entirely by one reference image, so that single
file silently sets the behaviour of two arms of the comparative study. Picking it by eye
would make those arms unauditable, and picking it from a target domain would leak target
information into them while leaving every reported number looking clean. The rule here
is fixed and recorded: the image whose mean LAB colour is closest to the median mean-LAB
over pbc_train -- the most typical source-domain image.

LEAKAGE. Reads pbc_train and nothing else. The dataset is built through the ordinary
loader path, so assert_source_only refuses anything that is not source data
(CLAUDE.md sec 3).
"""
from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

import numpy as np
import yaml
from PIL import Image
from skimage.color import rgb2lab

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from src.config import load_config                            # noqa: E402
from src.data.datasets import PbcWbcAttDataset               # noqa: E402
from src.data.domains import assert_source_only              # noqa: E402

TRAIN_SPLIT = "pbc_train"
OUT = REPO_ROOT / "configs" / "stain_reference.yaml"
SELECTION_RULE = ("image whose mean LAB colour is closest (Euclidean) to the median "
                  "mean-LAB over pbc_train")

HEADER = """# Stain reference for the Macenko and Reinhard arms (Phase II deck, objective 3).
#
# Generated by scripts/choose_stain_reference.py -- do not hand-edit.
# Chosen from the PBC TRAIN split only. A reference drawn from Raabin or LISC would leak
# target-domain information into both stain arms while leaving every reported number
# looking clean (CLAUDE.md sec 3).
#
# `path` is relative to paths.pbc_images.
"""


def mean_lab(path: Path) -> np.ndarray:
    with Image.open(path) as image:
        rgb = np.asarray(image.convert("RGB"), dtype=np.float64) / 255.0
    return rgb2lab(rgb).reshape(-1, 3).mean(axis=0)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--config", required=True)
    args = parser.parse_args(argv)

    cfg = load_config(args.config)
    assert_source_only(TRAIN_SPLIT)

    dataset = PbcWbcAttDataset(
        dataset_id=TRAIN_SPLIT,
        pbc_images=cfg.paths.pbc_images,
        wbcatt_dir=cfg.paths.wbcatt_dir,
        mapping=cfg.data.class_mapping,
        label_space=cfg.data.label_space,
        image_size=cfg.data.image_size,
        transform=None,
    )
    print(f"scanning {len(dataset.paths)} {TRAIN_SPLIT} images (source domain only)...",
          flush=True)

    started = time.time()
    means = []
    for i, path in enumerate(dataset.paths, 1):
        means.append(mean_lab(path))
        if i % 1000 == 0:
            print(f"  {i}/{len(dataset.paths)}", flush=True)
    means = np.vstack(means)

    median = np.median(means, axis=0)
    distances = np.linalg.norm(means - median, axis=1)
    winner = int(np.argmin(distances))
    chosen = Path(dataset.paths[winner])
    relative = chosen.relative_to(Path(cfg.paths.pbc_images).parent)

    document = {
        "path": relative.as_posix(),
        "img_name": chosen.name,
        "dataset": "pbc",
        "split": "train",
        "selection_rule": SELECTION_RULE,
        "candidates": len(dataset.paths),
        "median_lab": [round(float(v), 4) for v in median],
        "chosen_mean_lab": [round(float(v), 4) for v in means[winner]],
        "distance_to_median": round(float(distances[winner]), 6),
        "generated": time.strftime("%Y-%m-%d %H:%M:%S"),
    }
    OUT.write_text(HEADER + yaml.safe_dump(document, sort_keys=False), encoding="utf-8")

    print(f"\nreference: {document['path']}")
    print(f"  mean LAB {document['chosen_mean_lab']} vs median {document['median_lab']}")
    print(f"wrote {OUT.relative_to(REPO_ROOT)} in {time.time() - started:.0f}s")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
