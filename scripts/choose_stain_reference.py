"""Choose the stain reference image for Model 2, from the PBC train split alone.

Usage: python scripts/choose_stain_reference.py

Writes configs/stain_reference.yaml. Re-running it reproduces the same choice.

Why a script and not a hand-picked file: Macenko and Reinhard are both defined entirely
by their reference image, so that one file silently sets the behaviour of an entire arm
of the comparison. Picking it by eye would make the arm unauditable. The rule here is
"the image whose mean LAB colour is closest to the median over PBC train" -- the most
typical source-domain image, chosen deterministically and recorded with the statistics
it produced.

LEAKAGE: this reads data/raw/PBC_dataset_normal_DIB and the WBCAtt train CSV, nothing
else. Target domains are not opened, and the script refuses to look at them. Excluded
files from configs/class_mapping.yaml are skipped so the reference can never be one of
the duplicate or mislabelled images.
"""
import csv
import sys
import time
from pathlib import Path

import numpy as np
import yaml
from PIL import Image
from skimage.color import rgb2lab

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw"
TRAIN_CSV = RAW / "pbc_attr_v1_train.csv"
OUT = ROOT / "configs" / "stain_reference.yaml"

SELECTION_RULE = (
    "image whose mean LAB colour is closest (Euclidean) to the median mean-LAB over the "
    "PBC train split, after applying class_mapping.yaml exclusions"
)


def mean_lab(path):
    with Image.open(path) as image:
        rgb = np.asarray(image.convert("RGB"), dtype=np.float64) / 255.0
    return rgb2lab(rgb).reshape(-1, 3).mean(axis=0)


def main():
    sys.path.insert(0, str(ROOT))
    from src.data.mapping import load_label_space

    if not TRAIN_CSV.exists():
        sys.exit(f"missing {TRAIN_CSV}")
    excluded = load_label_space().excluded_image_names()

    with open(TRAIN_CSV, newline="", encoding="utf-8") as fh:
        rows = [r for r in csv.DictReader(fh) if r["img_name"] not in excluded]
    print(f"scanning {len(rows)} PBC train images (source domain only)...", flush=True)

    started = time.time()
    names, paths, means = [], [], []
    for i, row in enumerate(rows, 1):
        path = RAW / row["path"]
        names.append(row["img_name"])
        paths.append(row["path"])
        means.append(mean_lab(path))
        if i % 1000 == 0:
            print(f"  {i}/{len(rows)}", flush=True)

    means = np.vstack(means)
    median = np.median(means, axis=0)
    distances = np.linalg.norm(means - median, axis=1)
    winner = int(np.argmin(distances))

    reference = {
        "path": paths[winner],
        "img_name": names[winner],
        "dataset": "pbc",
        "split": "train",
        "selection_rule": SELECTION_RULE,
        "candidates": len(rows),
        "median_lab": [round(float(v), 4) for v in median],
        "chosen_mean_lab": [round(float(v), 4) for v in means[winner]],
        "distance_to_median": round(float(distances[winner]), 6),
        "generated": time.strftime("%Y-%m-%d %H:%M:%S"),
    }

    header = (
        "# Stain reference for Model 2 (Macenko and Reinhard).\n"
        "#\n"
        "# Generated by scripts/choose_stain_reference.py -- do not hand-edit.\n"
        "# Chosen from the PBC TRAIN split only. A reference drawn from Raabin or LISC\n"
        "# would leak target-domain information into models 2a and 2b while leaving every\n"
        "# reported number looking clean (CLAUDE.md section 3).\n"
    )
    OUT.write_text(header + yaml.safe_dump(reference, sort_keys=False), encoding="utf-8")
    print(f"\nreference: {reference['path']}")
    print(f"  mean LAB {reference['chosen_mean_lab']} vs median {reference['median_lab']}")
    print(f"  distance {reference['distance_to_median']}")
    print(f"wrote {OUT.relative_to(ROOT)} in {time.time() - started:.0f}s")


if __name__ == "__main__":
    main()
