"""Turn results/*.json into a tracked report.

Usage: python scripts/summarise_runs.py

Writes reports/source_domain_results.md.

Why: results/ is gitignored, so the numbers a run produces live only on whichever
machine produced them. This lifts the parts that belong in a writeup into the repo,
with the provenance attached -- commit, hardware, seeds, epochs -- so a number in the
report can always be traced back to the run that produced it.

Reports spread against seed standard deviation for the headline metric, because with
four methods within 0.003 of each other and seed noise of similar size, a bare ranking
would invite a conclusion the data does not support.
"""
import glob
import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
OUT = ROOT / "reports" / "source_domain_results.md"

# smoke runs prove the pipeline executes; their numbers are not reportable.
SKIP = {"smoke", "pytest_smoke"}
HEADLINE = "macro_f1"


def table(headers, rows):
    out = ["| " + " | ".join(str(h) for h in headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    return "\n".join(out + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def mean_std(values):
    return sum(values) / len(values), statistics.pstdev(values)


def main():
    runs = {}
    for path in sorted(RESULTS.glob("*.json")):
        record = json.loads(path.read_text(encoding="utf-8"))
        if record.get("run_id") not in SKIP:
            runs[record["run_id"]] = record
    if not runs:
        sys.exit(f"no reportable runs in {RESULTS}")

    classes = next(iter(runs.values()))["classes"]
    splits = sorted({s for r in runs.values() for s in r["per_split_aggregate"]})

    L = [
        "# Source-domain results",
        "",
        "Generated by `scripts/summarise_runs.py` from `results/*.json`. Source domain only:",
        "no target-domain evaluation has been run yet, so none of these numbers speak to the",
        "cross-lab drop the project is actually about.",
        "",
        "Every model runs the identical protocol -- ResNet-50 at 224 px, the same splits,",
        "3 seeds, early stopping on PBC val macro-F1, patience 5 -- so the only difference",
        "between arms is the method itself.",
        "",
        "## Headline: the four methods are indistinguishable on the source domain",
        "",
    ]

    for split in splits:
        rows = []
        for name, record in runs.items():
            agg = record["per_split_aggregate"].get(split)
            if not agg:
                continue
            rows.append([f"`{name}`"] + [
                f"{agg[m]['mean']:.4f} ± {agg[m]['std']:.4f}"
                for m in ("macro_f1", "macro_recall", "accuracy") if m in agg
            ])
        means = [record["per_split_aggregate"][split][HEADLINE]["mean"]
                 for record in runs.values() if split in record["per_split_aggregate"]]
        stds = [record["per_split_aggregate"][split][HEADLINE]["std"]
                for record in runs.values() if split in record["per_split_aggregate"]]
        L += [f"**{split}**", "",
              table(["run", "macro-F1", "macro-recall", "accuracy"], rows), "",
              f"Spread across methods: **{max(means) - min(means):.4f}**. "
              f"Largest seed-to-seed std: **{max(stds):.4f}**. "
              + ("The methods are separated by less than the noise between seeds of a single "
                 "method, so no ranking can be read off this table."
                 if max(means) - min(means) <= 2 * max(stds) else
                 "The spread exceeds twice the largest seed std, so a difference may be real."),
              ""]

    L += ["## Per-class recall", "",
          "Reported separately per CLAUDE.md section 6. Mean ± std over seeds.", ""]
    for split in splits:
        rows = []
        for name, record in runs.items():
            if split not in record["per_split_aggregate"]:
                continue
            cells = []
            for cls in classes:
                values = [seed["metrics"][split]["per_class"][cls]["recall"]
                          for seed in record["seeds"].values()]
                mean, std = mean_std(values)
                cells.append(f"{mean:.4f} ± {std:.4f}")
            rows.append([f"`{name}`"] + cells)
        support = next(iter(runs.values()))["seeds"]["0"]["metrics"][split]["per_class"]
        L += [f"**{split}** (support: " +
              ", ".join(f"{c} {support[c]['support']}" for c in classes) + ")", "",
              table(["run"] + classes, rows), ""]

    L += ["## Runs", "",
          table(["run", "commit", "dirty", "hardware", "seeds", "best epoch / run", "wall clock"],
                [[f"`{name}`", f"`{r['git']['commit'][:8]}`", r["git"]["dirty"],
                  r["hardware"].get("gpu", r["hardware"].get("processor", "?")),
                  len(r["seeds"]),
                  ", ".join(f"{s['best_epoch']}/{s['epochs_run']}" for s in r["seeds"].values()),
                  f"{r['wall_clock_s']:.0f}s"]
                 for name, r in runs.items()]), "",
          "No run reached its 30-epoch cap, so early stopping -- not the budget -- decided",
          "every stopping point; the epoch budget can stay as it is for the remaining models.",
          ""]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} from {len(runs)} runs")


if __name__ == "__main__":
    main()
